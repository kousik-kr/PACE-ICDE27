/**
 * Loader for the synthetic graph files generated by {@code generate_td_graph.py}.
 */
public final class GeneratedGraphLoader {
    private static final Pattern NUMBER_PATTERN = Pattern.compile("-?\\d+(?:\\.\\d+)?(?:[eE][+-]?\\d+)?");
    private static final Pattern SUPPORT_DESCRIPTION_PATTERN = Pattern.compile(
            "(?i)\\bpoints\\s+from\\s+(-?\\d+(?:\\.\\d+)?)\\s+through\\s+(-?\\d+(?:\\.\\d+)?)");
    private static final ObjectMapper JSON = new ObjectMapper();

    /**
     * Loads a generated graph directory.
     */
    public GeneratedGraphDataset load(Path directory) throws IOException {
        return load(directory, (component, elapsedNanos) -> { });
    }

    /** Loads a dataset and reports bounded input-stage durations to a caller. */
    public GeneratedGraphDataset load(
            Path directory,
            BiConsumer<String, Long> timingObserver) throws IOException {
        Objects.requireNonNull(directory, "directory");
        Objects.requireNonNull(timingObserver, "timingObserver");
        if (!Files.isDirectory(directory)) {
            throw new IOException("generated graph directory does not exist: " + directory);
        }

        long stageStarted = System.nanoTime();
        ManifestSummary manifest = readManifest(directory.resolve("manifest.json"));
        report(timingObserver, "manifest_loading", stageStarted);
        stageStarted = System.nanoTime();
        Map<Integer, Node> nodes = readNodes(directory.resolve("nodes.csv.gz"));
        report(timingObserver, "node_input_loading", stageStarted);
        stageStarted = System.nanoTime();
        List<EdgeBuilder> builders = readStaticEdges(directory.resolve("edges_static.csv.gz"));
        report(timingObserver, "static_graph_input_loading", stageStarted);
        stageStarted = System.nanoTime();
        readTravelTimeFunctions(directory.resolve("travel_time_functions.jsonl.gz"), builders);
        long temporalTravelNanos = System.nanoTime() - stageStarted;
        report(timingObserver, "temporal_travel_input_loading", stageStarted);
        stageStarted = System.nanoTime();
        readScoreFunctions(directory.resolve("score_functions.jsonl.gz"), builders);
        long temporalScoreNanos = System.nanoTime() - stageStarted;
        report(timingObserver, "temporal_score_input_loading", stageStarted);
        timingObserver.accept(
                "temporal_input_loading_total",
                temporalTravelNanos + temporalScoreNanos);

        long listedScoreFunctions = builders.stream()
                .filter(builder -> builder.scoreFunction != null)
                .count();
        if (manifest != null && listedScoreFunctions != manifest.selectedScoreEdgeCount()) {
            throw new IOException("manifest score-edge count mismatch: manifest="
                    + manifest.selectedScoreEdgeCount() + " loaded=" + listedScoreFunctions);
        }
        List<Edge> edges = new ArrayList<>(builders.size());
        for (EdgeBuilder builder : builders) {
            if (builder.travelTimeFunction == null) {
                throw new IOException("missing travel-time function for arc_id " + builder.arcId);
            }
            if (builder.scoreFunction == null) {
                if (manifest != null && !manifest.unlistedEdgesHaveScoreZero()) {
                    throw new IOException(
                            "missing score function for arc_id " + builder.arcId
                                    + " and manifest does not authorize zero scores for unlisted edges");
                }
                builder.scoreFunction = PiecewiseConstFn.constant(
                        builder.travelTimeFunction.domain(),
                        0);
            }
            edges.add(builder.toEdge());
        }

        stageStarted = System.nanoTime();
        TDGraph graph = new TDGraph(nodes.values(), edges);
        GraphValidator.validate(graph, false);

        if (manifest != null) {
            if (manifest.numNodes() != graph.nodeCount()) {
                throw new IOException("manifest node count mismatch: manifest=" + manifest.numNodes()
                        + " loaded=" + graph.nodeCount());
            }
            if (manifest.numArcs() != graph.edgeCount()) {
                throw new IOException("manifest arc count mismatch: manifest=" + manifest.numArcs()
                        + " loaded=" + graph.edgeCount());
            }
        }
        report(timingObserver, "graph_assembly_validation", stageStarted);

        return new GeneratedGraphDataset(graph, manifest, directory);
    }

    private static void report(
            BiConsumer<String, Long> timingObserver,
            String component,
            long startedNanos) {
        timingObserver.accept(component, System.nanoTime() - startedNanos);
    }

    /**
     * Loads a preparation dataset and enforces its declared conversion,
     * temporal support, FIFO, and strictly positive lower-bound invariants.
     */
    public GeneratedGraphDataset loadVerified(
            Path directory,
            String requiredConversionContract,
            double requiredSupportEnd) throws IOException {
        if (requiredConversionContract == null
                || requiredConversionContract.isBlank()) {
            throw new IllegalArgumentException(
                    "required conversion contract is required");
        }
        if (!Double.isFinite(requiredSupportEnd) || requiredSupportEnd <= 0) {
            throw new IllegalArgumentException(
                    "required support end must be finite and positive");
        }
        GeneratedGraphDataset dataset = load(directory);
        ManifestSummary manifest = dataset.manifest();
        if (manifest == null) {
            throw new IOException(directory + ": manifest.json is required");
        }
        String declaredContract = manifest.conversionContractId()
                .orElseThrow(() -> new IOException(
                        directory + ": manifest does not declare conversion_contract.contract_id"));
        if (!requiredConversionContract.equals(declaredContract)) {
            throw new IOException(
                    directory + ": conversion contract " + declaredContract
                            + " does not match required "
                            + requiredConversionContract);
        }
        ManifestSummary.TimeWindow support = manifest.temporalSupport()
                .orElseThrow(() -> new IOException(
                        directory + ": manifest does not declare temporal support"));
        if (support.endMinute() < requiredSupportEnd) {
            throw new IOException(
                    directory + ": temporal support ends at "
                            + support.endMinute() + "; requires "
                            + requiredSupportEnd);
        }
        Domain requiredDomain = Domain.closed(
                support.startMinute(), requiredSupportEnd);
        for (Edge edge : dataset.graph().edges()) {
            if (!edge.travelTimeFunction().isFifo()) {
                throw new IOException(
                        directory + ": arc_id " + edge.arcId()
                                + " has a non-FIFO arrival function");
            }
            double lowerBound = edge.travelTimeFunction().minTravelTime();
            if (!Double.isFinite(lowerBound) || lowerBound <= 0) {
                throw new IOException(
                        directory + ": arc_id " + edge.arcId()
                                + " has non-positive lower-bound travel time "
                                + lowerBound);
            }
            if (!requiredDomain.difference(
                    edge.travelTimeFunction().domain()).isEmpty()) {
                throw new IOException(
                        directory + ": arc_id " + edge.arcId()
                                + " travel-time support does not cover "
                                + requiredDomain);
            }
            if (!requiredDomain.difference(
                    edge.scoreFunction().domain()).isEmpty()) {
                throw new IOException(
                        directory + ": arc_id " + edge.arcId()
                                + " score support does not cover "
                                + requiredDomain);
            }
        }
        return dataset;
    }

    private static Map<Integer, Node> readNodes(Path path) throws IOException {
        Map<Integer, Node> nodes = new HashMap<>();
        try (BufferedReader reader = openMaybeGzip(path)) {
            String header = reader.readLine();
            if (!"node_id,x,y".equals(header)) {
                throw new IOException(path + ": invalid nodes header");
            }

            String line;
            long lineNumber = 1;
            while ((line = reader.readLine()) != null) {
                lineNumber++;
                if (line.isBlank()) {
                    continue;
                }
                String[] parts = line.split(",", -1);
                if (parts.length != 3) {
                    throw new IOException(path + ":" + lineNumber + ": invalid node row");
                }
                int id = parseInt(parts[0], path, lineNumber, "node_id");
                long x = parseLong(parts[1], path, lineNumber, "x");
                long y = parseLong(parts[2], path, lineNumber, "y");
                if (nodes.put(id, new Node(id, x, y)) != null) {
                    throw new IOException(path + ":" + lineNumber + ": duplicate node id " + id);
                }
            }
        }
        return nodes;
    }

    private static List<EdgeBuilder> readStaticEdges(Path path) throws IOException {
        List<EdgeBuilder> edges = new ArrayList<>();
        try (BufferedReader reader = openMaybeGzip(path)) {
            String header = reader.readLine();
            if (!"arc_id,u,v,distance,base_travel_time".equals(header)) {
                throw new IOException(path + ": invalid static edge header");
            }

            String line;
            long lineNumber = 1;
            while ((line = reader.readLine()) != null) {
                lineNumber++;
                if (line.isBlank()) {
                    continue;
                }
                String[] parts = line.split(",", -1);
                if (parts.length != 5) {
                    throw new IOException(path + ":" + lineNumber + ": invalid static edge row");
                }
                int arcId = parseInt(parts[0], path, lineNumber, "arc_id");
                if (arcId != edges.size()) {
                    throw new IOException(path + ":" + lineNumber + ": expected arc_id " + edges.size()
                            + " but found " + arcId);
                }
                EdgeBuilder builder = new EdgeBuilder();
                builder.arcId = arcId;
                builder.u = parseInt(parts[1], path, lineNumber, "u");
                builder.v = parseInt(parts[2], path, lineNumber, "v");
                builder.distance = parseLong(parts[3], path, lineNumber, "distance");
                builder.baseTravelTime = parseDouble(parts[4], path, lineNumber, "base_travel_time");
                edges.add(builder);
            }
        }
        return edges;
    }

    private static void readTravelTimeFunctions(Path path, List<EdgeBuilder> builders) throws IOException {
        try (BufferedReader reader = openMaybeGzip(path)) {
            String line;
            long lineNumber = 0;
            while ((line = reader.readLine()) != null) {
                lineNumber++;
                if (line.isBlank()) {
                    continue;
                }
                int arcId = intJsonField(line, "arc_id", path, lineNumber);
                EdgeBuilder builder = builderFor(builders, arcId, path, lineNumber);
                validateJsonEndpoint(line, builder, path, lineNumber);
                if (builder.travelTimeFunction != null) {
                    throw new IOException(
                            path + ":" + lineNumber
                                    + ": duplicate travel-time function for arc_id "
                                    + arcId);
                }
                double functionBase = doubleJsonField(
                        line, "base_travel_time", path, lineNumber);
                if (Domain.canonicalTime(functionBase)
                        != Domain.canonicalTime(builder.baseTravelTime)) {
                    throw new IOException(
                            path + ":" + lineNumber
                                    + ": base_travel_time mismatch for arc_id "
                                    + arcId + ": static=" + builder.baseTravelTime
                                    + " function=" + functionBase);
                }
                String array = jsonArrayField(line, "travel_time_breakpoints", path, lineNumber);
                builder.travelTimeFunction = new PiecewiseLinearFn(parseBreakpoints(array, path, lineNumber));
            }
        }
    }

    private static void readScoreFunctions(Path path, List<EdgeBuilder> builders) throws IOException {
        if (!Files.exists(path)) {
            return;
        }
        try (BufferedReader reader = openMaybeGzip(path)) {
            String line;
            long lineNumber = 0;
            while ((line = reader.readLine()) != null) {
                lineNumber++;
                if (line.isBlank()) {
                    continue;
                }
                int arcId = intJsonField(line, "arc_id", path, lineNumber);
                EdgeBuilder builder = builderFor(builders, arcId, path, lineNumber);
                validateJsonEndpoint(line, builder, path, lineNumber);
                if (builder.scoreFunction != null) {
                    throw new IOException(
                            path + ":" + lineNumber
                                    + ": duplicate score function for arc_id "
                                    + arcId);
                }
                String array = jsonArrayField(line, "score_intervals", path, lineNumber);
                builder.scoreFunction = new PiecewiseConstFn(parseScoreIntervals(array, path, lineNumber));
            }
        }
    }

    private static ManifestSummary readManifest(Path path) throws IOException {
        if (!Files.exists(path)) {
            return null;
        }
        JsonNode root = JSON.readTree(path.toFile());
        if (root == null || !root.isObject()) {
            throw new IOException(path + ": manifest root must be a JSON object");
        }
        try {
            return new ManifestSummary(
                    optionalInt(root, "schema_version", 1, path),
                    requiredInt(root, "num_nodes", path),
                    requiredInt(root, "num_arcs", path),
                    requiredLong(root, "seed", path),
                    requiredInt(root, "selected_score_edge_count", path),
                    requiredBoolean(root, "unlisted_edges_have_score_zero", path),
                    readTemporalSupport(root, path),
                    readRushWindows(root, path),
                    conversionContractId(root, path),
                    optionalText(root, "dataset_checksum", path),
                    optionalText(root, "temporal_attribute_checksum", path));
        } catch (IllegalArgumentException failure) {
            throw new IOException(path + ": invalid manifest: " + failure.getMessage(), failure);
        }
    }

    private static Optional<ManifestSummary.TimeWindow> readTemporalSupport(JsonNode root, Path path)
            throws IOException {
        JsonNode support = root.get("temporal_support");
        if (support == null || support.isNull()) {
            JsonNode output = root.get("travel_time_output");
            if (output != null && output.isObject()) {
                support = output.get("temporal_support");
            }
        }
        if (support != null && !support.isNull()) {
            return Optional.of(readWindow(support, "temporal_support", path));
        }

        JsonNode output = root.get("travel_time_output");
        JsonNode format = output == null ? null : output.get("format");
        if (format != null && format.isTextual()) {
            Matcher matcher = SUPPORT_DESCRIPTION_PATTERN.matcher(format.textValue());
            if (matcher.find()) {
                return Optional.of(new ManifestSummary.TimeWindow(
                        Double.parseDouble(matcher.group(1)),
                        Double.parseDouble(matcher.group(2))));
            }
        }
        return Optional.empty();
    }

    private static Map<String, ManifestSummary.TimeWindow> readRushWindows(JsonNode root, Path path)
            throws IOException {
        JsonNode rush = root.get("rush_windows");
        if (rush == null || rush.isNull()) {
            return Map.of();
        }
        if (!rush.isObject()) {
            throw new IOException(path + ": rush_windows must be a JSON object");
        }
        TreeMap<String, ManifestSummary.TimeWindow> result = new TreeMap<>();
        var fields = rush.fields();
        while (fields.hasNext()) {
            Map.Entry<String, JsonNode> field = fields.next();
            result.put(field.getKey(), readWindow(
                    field.getValue(), "rush_windows." + field.getKey(), path));
        }
        return result;
    }

    private static ManifestSummary.TimeWindow readWindow(JsonNode node, String field, Path path)
            throws IOException {
        double start;
        double end;
        if (node.isArray() && node.size() == 2
                && node.get(0).isNumber() && node.get(1).isNumber()) {
            start = node.get(0).doubleValue();
            end = node.get(1).doubleValue();
        } else if (node.isObject()) {
            JsonNode startNode = node.has("start") ? node.get("start") : node.get("start_minute");
            JsonNode endNode = node.has("end") ? node.get("end") : node.get("end_minute");
            if (startNode == null || endNode == null || !startNode.isNumber() || !endNode.isNumber()) {
                throw new IOException(path + ": " + field + " must define numeric start and end values");
            }
            start = startNode.doubleValue();
            end = endNode.doubleValue();
        } else {
            throw new IOException(path + ": " + field + " must be a two-value array or object");
        }
        try {
            return new ManifestSummary.TimeWindow(start, end);
        } catch (IllegalArgumentException failure) {
            throw new IOException(path + ": invalid " + field + ": " + failure.getMessage(), failure);
        }
    }

    private static int requiredInt(JsonNode root, String field, Path path) throws IOException {
        long value = requiredLong(root, field, path);
        if (value < Integer.MIN_VALUE || value > Integer.MAX_VALUE) {
            throw new IOException(path + ": integer field out of range: " + field);
        }
        return (int) value;
    }

    private static int optionalInt(
            JsonNode root,
            String field,
            int defaultValue,
            Path path) throws IOException {
        JsonNode value = root.get(field);
        if (value == null || value.isNull()) {
            return defaultValue;
        }
        if (!value.isIntegralNumber() || !value.canConvertToInt()) {
            throw new IOException(path + ": invalid integer JSON field " + field);
        }
        return value.intValue();
    }

    private static Optional<String> conversionContractId(
            JsonNode root,
            Path path) throws IOException {
        JsonNode conversion = root.get("conversion_contract");
        if (conversion == null || conversion.isNull()) {
            return Optional.empty();
        }
        if (!conversion.isObject()) {
            throw new IOException(path + ": conversion_contract must be an object");
        }
        return optionalText(conversion, "contract_id", path);
    }

    private static Optional<String> optionalText(
            JsonNode root,
            String field,
            Path path) throws IOException {
        JsonNode value = root.get(field);
        if (value == null || value.isNull()) {
            return Optional.empty();
        }
        if (!value.isTextual() || value.textValue().isBlank()) {
            throw new IOException(path + ": invalid text JSON field " + field);
        }
        return Optional.of(value.textValue());
    }

    private static long requiredLong(JsonNode root, String field, Path path) throws IOException {
        JsonNode value = root.get(field);
        if (value == null || !value.isIntegralNumber() || !value.canConvertToLong()) {
            throw new IOException(path + ": missing or invalid integer JSON field " + field);
        }
        return value.longValue();
    }

    private static boolean requiredBoolean(JsonNode root, String field, Path path) throws IOException {
        JsonNode value = root.get(field);
        if (value == null || !value.isBoolean()) {
            throw new IOException(path + ": missing or invalid boolean JSON field " + field);
        }
        return value.booleanValue();
    }

    private static BufferedReader openMaybeGzip(Path path) throws IOException {
        InputStream input = Files.newInputStream(path);
        if (path.getFileName().toString().endsWith(".gz")) {
            input = new GZIPInputStream(input);
        }
        return new BufferedReader(new InputStreamReader(input, StandardCharsets.UTF_8));
    }

    private static EdgeBuilder builderFor(List<EdgeBuilder> builders, int arcId, Path path, long lineNumber)
            throws IOException {
        if (arcId < 0 || arcId >= builders.size()) {
            throw new IOException(path + ":" + lineNumber + ": unknown arc_id " + arcId);
        }
        return builders.get(arcId);
    }

    private static void validateJsonEndpoint(String line, EdgeBuilder builder, Path path, long lineNumber)
            throws IOException {
        int u = intJsonField(line, "u", path, lineNumber);
        int v = intJsonField(line, "v", path, lineNumber);
        if (u != builder.u || v != builder.v) {
            throw new IOException(path + ":" + lineNumber + ": endpoint mismatch for arc_id " + builder.arcId);
        }
    }

    private static List<PiecewiseLinearFn.Breakpoint> parseBreakpoints(String array, Path path, long lineNumber)
            throws IOException {
        List<Double> numbers = numbers(array);
        if (numbers.size() % 2 != 0) {
            throw new IOException(path + ":" + lineNumber + ": breakpoint array must contain pairs");
        }
        List<PiecewiseLinearFn.Breakpoint> breakpoints = new ArrayList<>();
        for (int i = 0; i < numbers.size(); i += 2) {
            breakpoints.add(new PiecewiseLinearFn.Breakpoint(numbers.get(i), numbers.get(i + 1)));
        }
        return breakpoints;
    }

    private static List<PiecewiseConstFn.Interval> parseScoreIntervals(String array, Path path, long lineNumber)
            throws IOException {
        List<Double> numbers = numbers(array);
        if (numbers.size() % 3 != 0) {
            throw new IOException(path + ":" + lineNumber + ": score interval array must contain triples");
        }
        List<PiecewiseConstFn.Interval> intervals = new ArrayList<>();
        for (int i = 0; i < numbers.size(); i += 3) {
            double scoreNumber = numbers.get(i + 2);
            int score = (int) scoreNumber;
            if (score != scoreNumber) {
                throw new IOException(path + ":" + lineNumber + ": score must be an integer");
            }
            intervals.add(new PiecewiseConstFn.Interval(numbers.get(i), numbers.get(i + 1), score));
        }
        return intervals;
    }

    private static List<Double> numbers(String text) {
        Matcher matcher = NUMBER_PATTERN.matcher(text);
        List<Double> numbers = new ArrayList<>();
        while (matcher.find()) {
            numbers.add(Double.parseDouble(matcher.group()));
        }
        return numbers;
    }

    private static String jsonArrayField(String text, String field, Path path, long lineNumber) throws IOException {
        int key = text.indexOf("\"" + field + "\"");
        if (key < 0) {
            throw new IOException(path + ":" + lineNumber + ": missing JSON field " + field);
        }
        int start = text.indexOf('[', key);
        if (start < 0) {
            throw new IOException(path + ":" + lineNumber + ": missing array for JSON field " + field);
        }
        int depth = 0;
        for (int index = start; index < text.length(); index++) {
            char ch = text.charAt(index);
            if (ch == '[') {
                depth++;
            } else if (ch == ']') {
                depth--;
                if (depth == 0) {
                    return text.substring(start, index + 1);
                }
            }
        }
        throw new IOException(path + ":" + lineNumber + ": unterminated array for JSON field " + field);
    }

    private static int intJsonField(String text, String field, Path path, long lineNumber) throws IOException {
        long value = longJsonField(text, field, path, lineNumber);
        if (value < Integer.MIN_VALUE || value > Integer.MAX_VALUE) {
            throw new IOException(path + ":" + lineNumber + ": integer field out of range: " + field);
        }
        return (int) value;
    }

    private static long longJsonField(String text, String field, Path path, long lineNumber) throws IOException {
        Pattern pattern = Pattern.compile("\"" + Pattern.quote(field) + "\"\\s*:\\s*(-?\\d+)");
        Matcher matcher = pattern.matcher(text);
        if (!matcher.find()) {
            throw new IOException(path + ":" + lineNumber + ": missing integer JSON field " + field);
        }
        return Long.parseLong(matcher.group(1));
    }

    private static double doubleJsonField(
            String text,
            String field,
            Path path,
            long lineNumber) throws IOException {
        Pattern pattern = Pattern.compile(
                "\"" + Pattern.quote(field)
                        + "\"\\s*:\\s*(-?\\d+(?:\\.\\d+)?(?:[eE][+-]?\\d+)?)");
        Matcher matcher = pattern.matcher(text);
        if (!matcher.find()) {
            throw new IOException(
                    path + ":" + lineNumber
                            + ": missing numeric JSON field " + field);
        }
        double value = Double.parseDouble(matcher.group(1));
        if (!Double.isFinite(value)) {
            throw new IOException(
                    path + ":" + lineNumber
                            + ": non-finite JSON field " + field);
        }
        return value;
    }

    private static boolean booleanJsonField(String text, String field, Path path, long lineNumber) throws IOException {
        Pattern pattern = Pattern.compile("\"" + Pattern.quote(field) + "\"\\s*:\\s*(true|false)");
        Matcher matcher = pattern.matcher(text);
        if (!matcher.find()) {
            throw new IOException(path + ":" + lineNumber + ": missing boolean JSON field " + field);
        }
        return Boolean.parseBoolean(matcher.group(1));
    }

    private static int parseInt(String text, Path path, long lineNumber, String field) throws IOException {
        try {
            return Integer.parseInt(text);
        } catch (NumberFormatException ex) {
            throw new IOException(path + ":" + lineNumber + ": invalid integer " + field + ": " + text, ex);
        }
    }

    private static long parseLong(String text, Path path, long lineNumber, String field) throws IOException {
        try {
            return Long.parseLong(text);
        } catch (NumberFormatException ex) {
            throw new IOException(path + ":" + lineNumber + ": invalid long " + field + ": " + text, ex);
        }
    }

    private static double parseDouble(String text, Path path, long lineNumber, String field) throws IOException {
        try {
            return Double.parseDouble(text);
        } catch (NumberFormatException ex) {
            throw new IOException(path + ":" + lineNumber + ": invalid decimal " + field + ": " + text, ex);
        }
    }

    private static final class EdgeBuilder {
        private int arcId;
        private int u;
        private int v;
        private long distance;
        private double baseTravelTime;
        private PiecewiseLinearFn travelTimeFunction;
        private PiecewiseConstFn scoreFunction;

        private Edge toEdge() {
            return new Edge(arcId, u, v, distance, baseTravelTime, travelTimeFunction, scoreFunction);
        }
    }
}
